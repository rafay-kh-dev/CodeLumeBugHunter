def count_results(lines):
    passed = sum(1 for l in lines if "[PASS]" in l)
    warned = sum(1 for l in lines if "[WARN]" in l)
    failed = sum(1 for l in lines if "[FAIL]" in l)
    return passed, warned, failed

def run_checker(func, project, file_counts, has_next):
    params = list(inspect.signature(func).parameters.keys())
    if len(params) <= 1:
        result = func(project)
    else:
        kwargs = {}
        if "counts" in params:
            kwargs["counts"] = file_counts
        if "file_counts" in params:
            kwargs["file_counts"] = file_counts
        if "has_next" in params:
            kwargs["has_next"] = has_next
        if "is_next" in params:
            kwargs["is_next"] = has_next
        result = func(project, **kwargs)
    if result is None:
        return []
    return result

def build_report(project, sections, file_counts, project_type, only=None, skipped=None):
    total_pass = 0
    total_warn = 0
    total_fail = 0
    summary_rows = []
    for name, lines in sections:
        p, w, f = count_results(lines)
        total_pass += p
        total_warn += w
        total_fail += f
        summary_rows.append(f"| {name} | {p} | {w} | {f} |")
    total = total_pass + total_warn + total_fail
    score = 100
    if total > 0:
        score = int(((total_pass * 1.0 + total_warn * 0.5) / total) * 100)
    status = "Excellent" if score >= 90 else "Good" if score >= 70 else "Needs Improvement" if score >= 50 else "Critical"
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    out = []
    out.append("# CodeLume - Project Report")
    out.append("")
    out.append(f"**Project:** {project}")
    out.append(f"**Generated:** {now}")
    out.append(f"**Tool:** CodeLume Bug Hunter v1.0")
    if only:
        out.append(f"**Categories:** {only}")
    out.append(f"**Score:** {score} / 100 - {status}")
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append("| Category | PASS | WARN | FAIL |")
    out.append("|----------|------|------|------|")
    for row in summary_rows:
        out.append(row)
    out.append(f"| **Total** | **{total_pass}** | **{total_warn}** | **{total_fail}** |")
    out.append("")
    out.append("## Project Type")
    out.append("")
    for t in project_type:
        out.append(f"- {t}")
    out.append("")
    if skipped:
        out.append("## Skipped - Not in Tech Stack")
        out.append("")
        for cat, reason in skipped:
            out.append(f"- {cat}: {reason}")
        out.append("")
    out.append("## File Counts")
    out.append("")
    out.append("| Extension | Count |")
    out.append("|-----------|-------|")
    for ext, count in sorted(file_counts.items()):
        out.append(f"| {ext} | {count} |")
    out.append("")
    out.append("## Details")
    out.append("")
    for name, lines in sections:
        out.append(f"### {name}")
        out.append("")
        if not lines:
            out.append("No issues found.")
        else:
            for line in lines:
                out.append(line)
        out.append("")
    out.append("---")
    out.append("Generated by CodeLume Bug Hunter. Run `py codelume.py <project-path>` to re-scan.")
    return "\n".join(out)

def show_menu():
    print("Select category to scan:")
    names = list(CATEGORIES.keys())
    for i, name in enumerate(names, 1):
        print(f"  {i}. {name} - {', '.join(CATEGORIES[name])}")
    choice = input("Enter number (or comma separated, e.g. 1,2): ").strip()
    selected = []
    for part in choice.split(","):
        part = part.strip()
        if part.isdigit() and 1 <= int(part) <= len(names):
            selected.append(names[int(part) - 1])
    return ",".join(selected) if selected else "all"

def main(project_path=None, only=None, output=None):
    list_flag = False
    menu_flag = False
    if project_path is None:
        parser = argparse.ArgumentParser()
        parser.add_argument("path", nargs="?", help="Project path to scan")
        parser.add_argument("--only", dest="only", default=None, help="Only scan these categories, e.g. --only frontend or --only frontend,backend")
        parser.add_argument("--list", dest="list_categories", action="store_true", help="List all available categories")
        parser.add_argument("--menu", dest="menu", action="store_true", help="Show interactive category menu")
        parser.add_argument("--output", dest="output", default=None, help="Output report filename, e.g. --output my-report.md")
        args = parser.parse_args()
        project_path = args.path
        only = args.only
        output = args.output
        list_flag = args.list_categories
        menu_flag = args.menu
    if list_flag:
        for name in CATEGORIES:
            print(f"{name}: {', '.join(CATEGORIES[name])}")
        return
    if not project_path:
        print("Usage: py codelume.py <project-path> [--only frontend] [--menu] [--list] [--output report.md]")
        return
    if menu_flag:
        only = show_menu()
    project = Path(project_path).resolve()
    print(f"Scanning: {project}")
    if only:
        print(f"Categories: {only}")
    detected = detect_project_type(project)
    if isinstance(detected, tuple):
        project_type = detected[0]
        file_counts = detected[1] if len(detected) > 1 and isinstance(detected[1], dict) else {}
    else:
        project_type = detected
        file_counts = {}
    if not file_counts:
        file_counts = {}
        for f in project.rglob("*"):
            if f.is_file() and ".git" not in f.parts and "__pycache__" not in f.parts and "node_modules" not in f.parts:
                ext = f.suffix.lower() or "no-extension"
                file_counts[ext] = file_counts.get(ext, 0) + 1
    has_next = any("Next.js" in str(t) for t in project_type)
    print("Project Type:")
    for t in project_type:
        print(f"  - {t}")
    all_checkers = [
        ("SQL", check_sql_smart),
        ("Secrets", check_secrets_smart),
        ("Gitignore", check_gitignore_smart),
        ("HTML", check_html_smart),
        ("Python", check_python_smart),
        ("PHP", check_php_smart),
        ("CSS", check_css_smart),
        ("JSON", check_json_smart),
        ("Markdown", check_md_smart),
        ("JS", check_js_smart),
        ("Images", check_images),
        ("Backend", check_backend_universal),
        ("Frontend", check_frontend_smart),
        ("Architecture", check_architecture),
        ("Database", check_database_smart),
    ]
    if only:
        allowed = get_categories_for_only(only)
    else:
        allowed = [name for name, func in all_checkers]
    applicable, skipped = filter_by_stack(allowed, project_type, file_counts)
    if skipped:
        print("Skipped - Not in tech stack:")
        for cat, reason in skipped:
            print(f"  - {cat}: {reason}")
    if not applicable:
        print("No applicable categories found for this tech stack.")
        return
    all_checkers = [(name, func) for name, func in all_checkers if name in applicable]
    sections = []
    for name, func in all_checkers:
        sections.append((name, run_checker(func, project, file_counts, has_next)))
    for name, lines in sections:
        print(f"\n## {name}")
        for line in lines:
            print(line)
    report = build_report(project, sections, file_counts, project_type, only=only, skipped=skipped)
    if output:
        out_path = Path(output)
    else:
        project_name = project.name.lower().replace(" ", "-").replace("_", "-")
        timestamp = datetime.now().strftime("%Y-%m-%d")
        out_path = Path(f"codelume-report-{project_name}-{timestamp}.md")
    out_path.write_text(report, encoding="utf-8")
    print(f"\nReport saved: {out_path.resolve()}")

if __name__ == "__main__":
    main()