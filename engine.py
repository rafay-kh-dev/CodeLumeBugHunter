import argparse
import inspect
from datetime import datetime
from pathlib import Path

from core.project_detector import detect_project_type
from analyzers.sql import check_sql_smart
from analyzers.secrets import check_secrets_smart
from analyzers.gitignore import check_gitignore_smart
from analyzers.html import check_html_smart
from analyzers.python import check_python_smart
from analyzers.php import check_php_smart
from analyzers.css import check_css_smart
from analyzers.json import check_json_smart
from analyzers.js import check_js_smart
from analyzers.images import check_images
from analyzers.backend import check_backend_universal
from analyzers.markdown import check_md_smart
from analyzers.architecture import check_architecture

def count_results(lines):
    passed = sum(1 for l in lines if "[PASS]" in l)
    warned = sum(1 for l in lines if "[WARN]" in l)
    failed = sum(1 for l in lines if "[FAIL]" in l)
    return passed, warned, failed

def run_checker(func, project, file_counts, has_next):
    params = list(inspect.signature(func).parameters.keys())
    if len(params) <= 1:
        result = func(project)
    else:
        kwargs = {}
        if "counts" in params:
            kwargs["counts"] = file_counts
        if "file_counts" in params:
            kwargs["file_counts"] = file_counts
        if "has_next" in params:
            kwargs["has_next"] = has_next
        if "is_next" in params:
            kwargs["is_next"] = has_next
        result = func(project, **kwargs)
    if result is None:
        return []
    return result

def build_report(project, sections, file_counts, project_type):
    total_pass = 0
    total_warn = 0
    total_fail = 0
    summary_rows = []
    for name, lines in sections:
        p, w, f = count_results(lines)
        total_pass += p
        total_warn += w
        total_fail += f
        summary_rows.append(f"| {name} | {p} | {w} | {f} |")
    total = total_pass + total_warn + total_fail
    score = 100
    if total > 0:
        score = int(((total_pass * 1.0 + total_warn * 0.5) / total) * 100)
    status = "Excellent" if score >= 90 else "Good" if score >= 70 else "Needs Improvement" if score >= 50 else "Critical"
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    out = []
    out.append("# CodeLume - Project Report")
    out.append("")
    out.append(f"**Project:** {project}")
    out.append(f"**Generated:** {now}")
    out.append(f"**Tool:** CodeLume Bug Hunter v1.0")
    out.append(f"**Score:** {score} / 100 - {status}")
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append("| Category | PASS | WARN | FAIL |")
    out.append("|----------|------|------|------|")
    for row in summary_rows:
        out.append(row)
    out.append(f"| **Total** | **{total_pass}** | **{total_warn}** | **{total_fail}** |")
    out.append("")
    out.append("## Project Type")
    out.append("")
    for t in project_type:
        out.append(f"- {t}")
    out.append("")
    out.append("## File Counts")
    out.append("")
    out.append("| Extension | Count |")
    out.append("|-----------|-------|")
    for ext, count in sorted(file_counts.items()):
        out.append(f"| {ext} | {count} |")
    out.append("")
    out.append("## Details")
    out.append("")
    for name, lines in sections:
        out.append(f"### {name}")
        out.append("")
        if not lines:
            out.append("No issues found.")
        else:
            for line in lines:
                out.append(line)
        out.append("")
    out.append("---")
    out.append("Generated by CodeLume Bug Hunter. Run `py codelume.py <project-path>` to re-scan.")
    return "\n".join(out)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("path", help="Project path to scan")
    args = parser.parse_args()
    project = Path(args.path).resolve()
    print(f"Scanning: {project}")
    detected = detect_project_type(project)
    if isinstance(detected, tuple):
        project_type = detected[0]
        file_counts = detected[1] if len(detected) > 1 and isinstance(detected[1], dict) else {}
    else:
        project_type = detected
        file_counts = {}
    if not file_counts:
        file_counts = {}
        for f in project.rglob("*"):
            if f.is_file() and ".git" not in f.parts and "__pycache__" not in f.parts and "node_modules" not in f.parts:
                ext = f.suffix.lower() or "no-extension"
                file_counts[ext] = file_counts.get(ext, 0) + 1
    has_next = any("Next.js" in str(t) for t in project_type)
    print("Project Type:")
    for t in project_type:
        print(f"  - {t}")
    sections = []
    sections.append(("SQL", run_checker(check_sql_smart, project, file_counts, has_next)))
    sections.append(("Secrets", run_checker(check_secrets_smart, project, file_counts, has_next)))
    sections.append(("Gitignore", run_checker(check_gitignore_smart, project, file_counts, has_next)))
    sections.append(("HTML", run_checker(check_html_smart, project, file_counts, has_next)))
    sections.append(("Python", run_checker(check_python_smart, project, file_counts, has_next)))
    sections.append(("PHP", run_checker(check_php_smart, project, file_counts, has_next)))
    sections.append(("CSS", run_checker(check_css_smart, project, file_counts, has_next)))
    sections.append(("JSON", run_checker(check_json_smart, project, file_counts, has_next)))
    sections.append(("Markdown", run_checker(check_md_smart, project, file_counts, has_next)))
    sections.append(("JS", run_checker(check_js_smart, project, file_counts, has_next)))
    sections.append(("Images", run_checker(check_images, project, file_counts, has_next)))
    sections.append(("Backend", run_checker(check_backend_universal, project, file_counts, has_next)))
    try:
        arch_lines = check_architecture(project)
        if arch_lines:
            for line in arch_lines:
                print(line)
    except:
        pass
    for name, lines in sections:
        print(f"\n## {name}")
        for line in lines:
            print(line)
    report = build_report(project, sections, file_counts, project_type)
    out_path = Path("performance_report.md")
    out_path.write_text(report, encoding="utf-8")
    print(f"\nReport saved: {out_path.resolve()}")

if __name__ == "__main__":
    main()